-- Lennox: Hyprland for Arch, in the spirit of ML4W.
--
-- Almost everything here is driven by Lennox Settings (SUPER + I), which
-- writes ~/.config/hypr/lennox/settings.lua. Put your own tweaks in
-- ~/.config/hypr/custom.lua: it loads last, so it wins over everything,
-- and Lennox updates never touch it.

-- Load a module without letting a missing or broken file take the whole
-- config down with it.
local function load(name)
    local ok, err = pcall(require, name)
    if not ok then
        print("[lennox] could not load " .. name .. ": " .. tostring(err))
    end
end

-- Helpers, defaults and your saved settings (defines LENNOX)
load("lennox.lib")

-- Wallpaper colors, generated by matugen on every wallpaper change
load("colors")

-- Monitors and workspace placement (nwg-displays writes these two)
load("lennox.monitors")
load("monitors")
load("workspaces")

-- Everything else
load("lennox.env")
load("lennox.input")
load("lennox.gestures")
load("lennox.look")
load("lennox.animation")
load("lennox.layout")
load("lennox.misc")
load("lennox.rules")
load("lennox.keybinds")
load("lennox.minimize")
load("lennox.modes")
load("lennox.autostart")

-- Your personal overrides
local custom = io.open(os.getenv("HOME") .. "/.config/hypr/custom.lua", "r")
if custom then
    custom:close()
    load("custom")
end
