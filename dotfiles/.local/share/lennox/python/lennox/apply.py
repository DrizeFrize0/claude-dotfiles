"""Turn settings.json into the config files the desktop actually reads.

Each "part" writes its files and, when running inside Hyprland, reloads
whatever reads them. Lennox Settings calls `lennox-apply <part>` after a
change; `lennox-apply all` regenerates everything.
"""

import os
import shutil
import subprocess
import sys
import tempfile

from . import settings as S

HOME = S.HOME
CONFIG = os.path.join(HOME, ".config")
BIN = os.path.join(HOME, ".local", "bin")


# ---------------------------------------------------------------- helpers

def in_session():
    return bool(os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"))


def write_file(path, content):
    """Write atomically, and only if the content changed. Returns True if written."""
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == content:
                return False
    except OSError:
        pass
    directory = os.path.dirname(path)
    os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".lennox-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(content)
    os.replace(tmp, path)
    return True


def run(cmd, quiet=True):
    """Run a command, never raising. Returns the exit code."""
    try:
        return subprocess.run(
            cmd,
            stdout=subprocess.DEVNULL if quiet else None,
            stderr=subprocess.DEVNULL if quiet else None,
            timeout=20,
            check=False,
        ).returncode
    except (OSError, subprocess.SubprocessError):
        return 1


def spawn(cmd):
    """Start a background process detached from us."""
    try:
        subprocess.Popen(
            cmd,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
    except OSError:
        pass


def have(program):
    return shutil.which(program) is not None


def restart(program, args=()):
    run(["pkill", "-x", program])
    spawn([program, *args])


# ---------------------------------------------------------------- hyprland

LUA_SECTIONS = ("appearance", "display", "input", "touchpad", "keybinds")


def lua_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    text = str(value)
    text = "".join(ch for ch in text if ch == "\n" or ord(ch) >= 32)
    text = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + text + '"'


def render_settings_lua(s):
    lines = [
        "-- Generated by lennox-apply from ~/.config/lennox/settings.json.",
        "-- Do not edit: change settings in Lennox Settings (SUPER + I),",
        "-- or put overrides in ~/.config/hypr/custom.lua.",
        "LENNOX_SETTINGS = {",
    ]
    for section in LUA_SECTIONS:
        lines.append(f"    {section} = {{")
        for key, value in s[section].items():
            lines.append(f"        {key} = {lua_value(value)},")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def apply_hypr(s, reload=True):
    path = os.path.join(CONFIG, "hypr", "lennox", "settings.lua")
    changed = write_file(path, render_settings_lua(s))
    if reload and changed and in_session():
        run(["hyprctl", "reload"])


# ---------------------------------------------------------------- idle

def render_hypridle(s):
    idle = s["idle"]
    dpms_on = "hyprctl dispatch 'hl.dsp.dpms({ action = \"enable\" })'"
    dpms_off = "hyprctl dispatch 'hl.dsp.dpms({ action = \"disable\" })'"
    out = [
        "# Generated by lennox-apply. Change these in Lennox Settings > Power.",
        "general {",
        f"    lock_cmd = {os.path.join(BIN, 'lennox-power')} lock",
    ]
    if idle["lock_before_sleep"]:
        out.append("    before_sleep_cmd = loginctl lock-session")
    out += [
        f"    after_sleep_cmd = {dpms_on}",
        "}",
        "",
    ]

    def listener(minutes, on_timeout, on_resume=None):
        if minutes <= 0:
            return
        out.append("listener {")
        out.append(f"    timeout = {int(minutes * 60)}")
        out.append(f"    on-timeout = {on_timeout}")
        if on_resume:
            out.append(f"    on-resume = {on_resume}")
        out.append("}")
        out.append("")

    listener(idle["dim_minutes"], "brightnessctl -s set 10%", "brightnessctl -r")
    listener(idle["lock_minutes"], "loginctl lock-session")
    listener(idle["screen_off_minutes"], dpms_off, f"{dpms_on} && brightnessctl -r")
    listener(idle["suspend_minutes"], f"{BIN}/lennox-power idle-suspend")
    # Sleep stats: 5 idle minutes don't count as still using the laptop
    listener(5, f"{BIN}/lennox-winddown away", f"{BIN}/lennox-winddown back")
    return "\n".join(out)


def apply_idle(s, reload=True):
    path = os.path.join(CONFIG, "hypr", "hypridle.conf")
    changed = write_file(path, render_hypridle(s))
    if reload and changed and in_session() and have("hypridle"):
        restart("hypridle")


# ---------------------------------------------------------------- night

def render_hyprsunset(s):
    night = s["night"]
    out = ["# Generated by lennox-apply. Change this in Lennox Settings > Night."]
    if night["nightlight"]:
        out += [
            "profile {",
            f"    time = {night['end']}",
            "    identity = true",
            "}",
            "",
            "profile {",
            f"    time = {night['start']}",
            f"    temperature = {night['temperature']}",
            "}",
        ]
    else:
        out += [
            "profile {",
            "    time = 00:00",
            "    identity = true",
            "}",
        ]
    return "\n".join(out) + "\n"


# Wind-down and sleep stats (lennox-winddown): name -> (what, command, when)
NIGHT_JOBS = {
    "lennox-winddown": ("Lennox wind-down", "start", "*-*-* {bedtime}:00"),
    "lennox-winddown-morning": ("Lennox wind-down: morning", "morning", "*-*-* {morning}:00"),
    "lennox-sleep-track": ("Lennox sleep stats", "track", "*-*-* 00..05,18..23:00/10:00"),
    "lennox-sleep-week": ("Lennox weekly sleep summary", "weekly", "Mon *-*-* 12:00:00"),
}

NIGHT_SERVICE = """[Unit]
Description={what}

[Service]
Type=oneshot
ExecStart=%h/.local/bin/lennox-winddown {command}
"""

NIGHT_TIMER = """[Unit]
Description={what}

[Timer]
OnCalendar={when}
AccuracySec=30s
Persistent={persistent}

[Install]
WantedBy=timers.target
"""


def apply_night(s, reload=True):
    night = s["night"]
    changed = write_file(os.path.join(CONFIG, "hypr", "hyprsunset.conf"), render_hyprsunset(s))
    if reload and changed and in_session() and have("hyprsunset"):
        # A manual toggle only lasts until the schedule changes
        try:
            os.remove(os.path.join(S.RUNTIME_DIR, "nightlight"))
        except OSError:
            pass
        restart("hyprsunset")

    units = os.path.join(CONFIG, "systemd", "user")
    times = {"bedtime": night["winddown_time"], "morning": night["end"]}
    times = {k: "{:02d}:{:02d}".format(*(int(x) for x in v.split(":"))) for k, v in times.items()}
    wanted = {
        "lennox-winddown": night["winddown"],
        "lennox-winddown-morning": night["winddown"],
        "lennox-sleep-track": night["sleep_stats"],
        "lennox-sleep-week": night["sleep_stats"],
    }
    units_changed = False
    for name, (what, command, when) in NIGHT_JOBS.items():
        units_changed |= write_file(os.path.join(units, f"{name}.service"),
                                    NIGHT_SERVICE.format(what=what, command=command))
        units_changed |= write_file(os.path.join(units, f"{name}.timer"), NIGHT_TIMER.format(
            what=what, when=when.format(**times),
            # The weekly summary still comes if the laptop was off on Monday noon
            persistent="true" if name == "lennox-sleep-week" else "false"))
    if not have("systemctl"):
        return
    if units_changed:
        run(["systemctl", "--user", "daemon-reload"])
    for name, on in wanted.items():
        if on:
            run(["systemctl", "--user", "enable", f"{name}.timer"])
            run(["systemctl", "--user", "restart", f"{name}.timer"])
        else:
            run(["systemctl", "--user", "disable", "--now", f"{name}.timer"])


# ---------------------------------------------------------------- wallpaper timer

WALLPAPER_SERVICE = """[Unit]
Description=Lennox random wallpaper

[Service]
Type=oneshot
ExecStart=%h/.local/bin/lennox-wallpaper --random --quiet
"""

WALLPAPER_TIMER = """[Unit]
Description=Lennox random wallpaper

[Timer]
OnActiveSec={minutes}min
OnUnitActiveSec={minutes}min

[Install]
WantedBy=timers.target
"""


def apply_wallpaper_timer(s, reload=True):
    minutes = s["wallpaper"]["auto_change_minutes"]
    units = os.path.join(CONFIG, "systemd", "user")
    changed = write_file(os.path.join(units, "lennox-wallpaper.service"), WALLPAPER_SERVICE)
    changed |= write_file(os.path.join(units, "lennox-wallpaper.timer"),
                          WALLPAPER_TIMER.format(minutes=max(minutes, 1)))
    if not have("systemctl"):
        return
    if changed:
        run(["systemctl", "--user", "daemon-reload"])
    if minutes > 0:
        run(["systemctl", "--user", "enable", "lennox-wallpaper.timer"])
        run(["systemctl", "--user", "restart", "lennox-wallpaper.timer"])
    else:
        run(["systemctl", "--user", "disable", "--now", "lennox-wallpaper.timer"])


# ---------------------------------------------------------------- gtk / qt / kitty

def button_layout(s):
    """Title bar buttons in apps. Minimize always works (lennox/minimize.lua);
    maximize only in stacking mode, since tiling ignores maximize requests."""
    if s["appearance"]["window_mode"] == "stacking":
        return "appmenu:minimize,maximize,close"
    return "appmenu:minimize,close"


def render_gtk(s, gtk4):
    a = s["appearance"]
    dark = a["color_mode"] == "dark"
    lines = [
        "[Settings]",
        f"gtk-theme-name={'adw-gtk3-dark' if dark else 'adw-gtk3'}",
        f"gtk-icon-theme-name={a['icon_theme']}",
        f"gtk-font-name={a['font']}",
        f"gtk-cursor-theme-name={a['cursor_theme']}",
        f"gtk-cursor-theme-size={a['cursor_size']}",
        f"gtk-decoration-layout={button_layout(s)}",
    ]
    if not gtk4:
        # libadwaita (GTK4) reads dark mode from the color-scheme setting
        # instead, and warns if this key is present in gtk-4.0/settings.ini
        lines.append(f"gtk-application-prefer-dark-theme={'true' if dark else 'false'}")
        lines += [
            "gtk-toolbar-style=GTK_TOOLBAR_ICONS",
            "gtk-button-images=0",
            "gtk-menu-images=0",
            "gtk-enable-event-sounds=0",
            "gtk-xft-antialias=1",
            "gtk-xft-hinting=1",
            "gtk-xft-hintstyle=hintslight",
            "gtk-xft-rgba=rgb",
        ]
    return "\n".join(lines) + "\n"


def set_ini_value(path, section, key, value):
    """Set key=value inside [section] of a simple ini file, keeping the rest."""
    try:
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()
    except OSError:
        lines = []
    header = f"[{section}]"
    entry = f"{key}={value}"
    if header not in (line.strip() for line in lines):
        lines += ["", header, entry] if lines else [header, entry]
    else:
        start = next(i for i, line in enumerate(lines) if line.strip() == header)
        end = next((i for i in range(start + 1, len(lines))
                    if lines[i].strip().startswith("[")), len(lines))
        for i in range(start + 1, end):
            if lines[i].split("=", 1)[0].strip() == key:
                lines[i] = entry
                break
        else:
            lines.insert(start + 1, entry)
    write_file(path, "\n".join(lines) + "\n")


def apply_gtk(s, reload=True):
    a = s["appearance"]
    write_file(os.path.join(CONFIG, "gtk-3.0", "settings.ini"), render_gtk(s, gtk4=False))
    write_file(os.path.join(CONFIG, "gtk-4.0", "settings.ini"), render_gtk(s, gtk4=True))

    qt = os.path.join(CONFIG, "qt6ct", "qt6ct.conf")
    if os.path.exists(qt):
        set_ini_value(qt, "Appearance", "icon_theme", a["icon_theme"])
        set_ini_value(qt, "Appearance", "color_scheme_path",
                      os.path.join(CONFIG, "qt6ct", "colors", "lennox.conf"))

    write_file(os.path.join(CONFIG, "kitty", "lennox-settings.conf"),
               "# Generated by lennox-apply\n"
               f"background_opacity {a['terminal_opacity']}\n")

    if not reload:
        return
    dark = a["color_mode"] == "dark"
    if have("gsettings"):
        schema = "org.gnome.desktop.interface"
        for key, value in (
            ("gtk-theme", "adw-gtk3-dark" if dark else "adw-gtk3"),
            ("icon-theme", a["icon_theme"]),
            ("cursor-theme", a["cursor_theme"]),
            ("cursor-size", str(a["cursor_size"])),
            ("font-name", a["font"]),
            ("color-scheme", "prefer-dark" if dark else "prefer-light"),
        ):
            run(["gsettings", "set", schema, key, value])
        # GTK4 / libadwaita apps read their title bar buttons from here
        run(["gsettings", "set", "org.gnome.desktop.wm.preferences", "button-layout", button_layout(s)])
    if in_session():
        run(["hyprctl", "setcursor", a["cursor_theme"], str(a["cursor_size"])])
        run(["pkill", "-USR1", "-x", "kitty"])


# ---------------------------------------------------------------- bar / dock

def apply_bar(s, reload=True):
    if reload and in_session():
        spawn([os.path.join(BIN, "lennox-bar"), "reload"])


def apply_aispend(s, reload=True):
    # The AI spend bar item re-reads its settings when poked
    if reload and in_session():
        run(["pkill", "-RTMIN+13", "-x", "waybar"])


def apply_dock(s, reload=True):
    if reload and in_session():
        spawn([os.path.join(BIN, "lennox-dock"), "reload"])


def apply_widgets(s, reload=True):
    # The running widgets re-read settings.json (and start if not running)
    if reload and in_session():
        spawn([os.path.join(BIN, "lennox-widgets"), "reload"])


def apply_theme(s, reload=True):
    """Color mode or scheme changed: re-run the wallpaper theming."""
    apply_gtk(s, reload)
    if reload:
        spawn([os.path.join(BIN, "lennox-wallpaper"), "--restore", "--theme-only", "--quiet"])


PARTS = {
    "hypr": apply_hypr,
    "idle": apply_idle,
    "night": apply_night,
    "wallpaper": apply_wallpaper_timer,
    "gtk": apply_gtk,
    "bar": apply_bar,
    "aispend": apply_aispend,
    "dock": apply_dock,
    "widgets": apply_widgets,
    "theme": apply_theme,
}


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    reload = True
    if "--no-reload" in argv:
        argv.remove("--no-reload")
        reload = False
    if not argv or argv == ["all"]:
        parts = ["hypr", "idle", "night", "wallpaper", "gtk", "bar", "dock", "widgets"]
    else:
        parts = argv
    unknown = [p for p in parts if p not in PARTS]
    if unknown:
        print(f"lennox-apply: unknown part(s): {', '.join(unknown)}", file=sys.stderr)
        print(f"usage: lennox-apply [--no-reload] [all | {' | '.join(PARTS)} ...]", file=sys.stderr)
        return 2
    s = S.load()
    for part in parts:
        PARTS[part](s, reload)
    return 0


if __name__ == "__main__":
    sys.exit(main())
